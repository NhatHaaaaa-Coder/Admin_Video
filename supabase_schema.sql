-- 1. BẢNG USERS (Quản lý tài khoản và phân quyền ADMIN / USER)
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'USER' CHECK (role IN ('ADMIN', 'USER')),
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_users_email ON public.users(email);
CREATE INDEX IF NOT EXISTS idx_users_role ON public.users(role);

-- 2. BẢNG VIDEO_CATEGORIES (Danh mục video)
CREATE TABLE IF NOT EXISTS public.video_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 3. BẢNG VIDEOS (Metadata video, lượt xem, dung lượng)
CREATE TABLE IF NOT EXISTS public.videos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT,
    thumbnail_url TEXT,
    video_url TEXT,
    category_id BIGINT REFERENCES public.video_categories(id) ON DELETE SET NULL,
    views BIGINT NOT NULL DEFAULT 0 CHECK (views >= 0),
    file_size_bytes BIGINT NOT NULL DEFAULT 0 CHECK (file_size_bytes >= 0),
    duration_seconds BIGINT NOT NULL DEFAULT 0 CHECK (duration_seconds >= 0),
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_videos_title ON public.videos(title);
CREATE INDEX IF NOT EXISTS idx_videos_views ON public.videos(views DESC);
CREATE INDEX IF NOT EXISTS idx_videos_category ON public.videos(category_id);

-- 4. BẢNG VIDEO_VIEW_STATS (Thống kê lượt xem theo ngày/tháng)
CREATE TABLE IF NOT EXISTS public.video_view_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id BIGINT NOT NULL REFERENCES public.videos(id) ON DELETE CASCADE,
    view_date DATE NOT NULL,
    views BIGINT NOT NULL DEFAULT 0 CHECK (views >= 0),
    UNIQUE(video_id, view_date)
);

CREATE INDEX IF NOT EXISTS idx_video_view_stats_date ON public.video_view_stats(view_date);

