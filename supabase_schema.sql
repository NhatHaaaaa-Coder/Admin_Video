-- Seed 30-day view statistics for demo charts
DO $$
DECLARE
    v RECORD;
    d INT;
    stat_date DATE;
    daily_views INT;
    base_views INT;
    day_factor FLOAT;
BEGIN
    FOR v IN SELECT id, views FROM public.videos LOOP
        base_views := GREATEST(10, ROUND(v.views / 45.0));
        FOR d IN 0..29 LOOP
            stat_date := CURRENT_DATE - (29 - d);
            -- Weekend boost
            IF EXTRACT(DOW FROM stat_date) IN (0, 6) THEN
                day_factor := 1.4;
            ELSE
                day_factor := 0.95;
            END IF;
            daily_views := GREATEST(5, ROUND(base_views * day_factor * (0.8 + (RANDOM() * 0.4))));
            INSERT INTO public.video_view_stats (video_id, view_date, views)
            VALUES (v.id, stat_date, daily_views)
            ON CONFLICT (video_id, view_date) DO UPDATE SET views = EXCLUDED.views;
        END LOOP;
    END LOOP;
END $$;
